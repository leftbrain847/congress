"""Assemble the static site (GitHub Pages) from site/, the built data and the self-hosted DuckDB-WASM.

  npm ci && python -m pipeline.build_site --data build/data --out build/site

- settings.json   front-end mirror of config/settings.yaml (analysis, scope, topic labels)
- js/engine.bundle.mjs  site/js/engine_duckdb.mjs + DuckDB-WASM's JS API + Arrow, bundled by esbuild
- vendor/         DuckDB-WASM workers and wasm (from node_modules) and its parquet extension (downloaded once from
                  extensions.duckdb.org), each checked against the sha256 in config/vendor.lock.json
- data/           the pipeline output (manifest.json lists every file the page may load)
Nothing is loaded from another origin at runtime.
"""
import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

from . import settings as settings_mod
from .queries import SQL_DIR
from .settings import ROOT

VENDOR_LOCK = ROOT / "config" / "vendor.lock.json"
EXT_CACHE = ROOT / "build" / "cache" / "extensions"
DUCKDB_DIST = ROOT / "node_modules" / "@duckdb" / "duckdb-wasm" / "dist"
STATIC = ["index.html", "css/app.css", "js/metrics.js", "js/app.js"]


def front_settings(cfg: dict) -> dict:
    return {
        "analysis": cfg["analysis"],
        "scope": cfg["scope"],
        "topics": {"pap_major_topics": {str(k): v for k, v in cfg["topics"]["pap_major_topics"].items()},
                   "crs_inherit_scope": cfg["topics"]["crs_inherit_scope"]},
    }


def sql_module() -> str:
    texts = {p.stem: p.read_text(encoding="utf-8") for p in sorted(SQL_DIR.glob("*.sql"))}
    return "// Generated by pipeline/build_site.py from site/sql/*.sql. Do not edit.\nexport default " + json.dumps(texts, indent=1) + ";\n"


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def copy_vendor(out: Path, update_lock: bool = False) -> dict:
    lock = json.loads(VENDOR_LOCK.read_text())
    got = {}
    (out / "vendor").mkdir(parents=True, exist_ok=True)
    for name in lock["files"]:
        src = DUCKDB_DIST / name
        if not src.exists():
            raise SystemExit(f"missing {src}: run npm ci first")
        got[name] = sha256(src)
        if not update_lock and got[name] != lock["files"][name]:
            raise SystemExit(f"{name}: sha256 {got[name]} does not match config/vendor.lock.json; refusing to ship it")
        shutil.copyfile(src, out / "vendor" / name)
    ext_got = {}
    for rel in lock.get("extensions", {}):
        cached = EXT_CACHE / rel
        if not cached.exists():
            cached.parent.mkdir(parents=True, exist_ok=True)
            req = urllib.request.Request(f"{lock['extension_source']}/{rel}", headers={"User-Agent": "congress-build"})
            with urllib.request.urlopen(req, timeout=120) as r:
                cached.write_bytes(r.read())
        ext_got[rel] = sha256(cached)
        if not update_lock and ext_got[rel] != lock["extensions"][rel]:
            cached.unlink()
            raise SystemExit(f"{rel}: sha256 {ext_got[rel]} does not match config/vendor.lock.json; refusing to ship it")
        dest = out / "vendor" / "extensions" / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(cached, dest)
    if update_lock:
        lock["files"], lock["extensions"] = got, ext_got
        VENDOR_LOCK.write_text(json.dumps(lock, indent=1) + "\n")
    return got


def bundle(out: Path):
    (ROOT / "site" / "js" / "sql.generated.js").write_text(sql_module(), encoding="utf-8")
    esbuild = ROOT / "node_modules" / ".bin" / "esbuild"
    subprocess.run([str(esbuild), str(ROOT / "site" / "js" / "engine_duckdb.mjs"), "--bundle", "--format=esm",
                    "--minify", "--target=es2020", "--legal-comments=eof", f"--outfile={out / 'js' / 'engine.bundle.mjs'}"],
                   check=True)


def build_site(data: Path, out: Path, cfg: dict, update_lock: bool = False):
    if out.exists():
        shutil.rmtree(out)
    for rel in STATIC:
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / "site" / rel, out / rel)
    (out / "settings.json").write_text(json.dumps(front_settings(cfg), indent=1))
    (out / ".nojekyll").write_text("")
    copy_vendor(out, update_lock)
    bundle(out)
    shutil.copytree(data, out / "data")


def main(argv=None) -> int:
    cfg = settings_mod.load()
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=cfg["output"]["data_dir"])
    ap.add_argument("--out", default="build/site")
    ap.add_argument("--update-vendor-lock", action="store_true", help="record new hashes after a deliberate DuckDB-WASM upgrade")
    args = ap.parse_args(argv)
    build_site(Path(args.data), Path(args.out), cfg, args.update_vendor_lock)
    print(f"site: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
